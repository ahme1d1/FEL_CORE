/**
 * The app-zone English keyset — canonical for `@fel/core/client`, and the shape `ar.ts` is typed
 * against, so a missing Arabic translation is a compile error here rather than a blank on a screen.
 *
 * Step 28b split the website's single 1,170-key dictionary in two. The 430 `marketing.*` keys stayed
 * in `FEL_WEBSITE/i18n/marketing.{ar,en}.ts`: landing-page and guide copy a phone will never render,
 * edited weekly, and a tagged package would turn every copy tweak into edit → tag → bump. These ~742
 * are what an app zone actually says, so they travel with the services that emit them.
 *
 * Three things about this file are load-bearing:
 *
 *   1. **`as const` is not decoration.** Without it `CoreKey` widens to `string` and every guard
 *      built on it — the AR parity annotation, `contract.ts`, the consumer's `Key` union — silently
 *      passes anything.
 *   2. **The keys are FLAT with dots.** `'points.breakdown.goals'` is one property, not three nested
 *      objects. vue-i18n's default resolver splits on `.` and would miss all of them, so
 *      `FEL_WEBSITE/i18n/i18n.config.ts` overrides `messageResolver` with a direct property read.
 *      A React client needs its own equivalent — see the README.
 *   3. **Values may contain a literal `@`** (`privacy@fantasyeg.com`). vue-i18n's default compiler
 *      reads that as a linked-message marker and throws `Invalid linked format`, which is why the
 *      same config overrides `messageCompiler` too. Interpolation here is only `{name}`/`{index}`.
 *
 * Add a string by adding the key here AND to `ar.ts`; the compiler enforces the second half.
 */
